export function getZoneAt(x, z) {
  for (const zone of ZONES) {
    const dx = x - zone.x;
    const dz = z - zone.z;
    if (Math.hypot(dx, dz) <= zone.radius) {
      return zone;
    }
  }
  return null;
}
